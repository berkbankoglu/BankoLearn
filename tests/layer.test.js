import { store, events, reloads, sleep, ok, done } from './env.js';
const sync = await import('../src/sync.js');
const sb = await import('../src/supabase.js');
const { clearAccountData } = await import('../src/utils/accounts.js');
const cloud = () => globalThis.__cloud;
const upserts = () => cloud().calls.filter(c => c[0] === 'upsert' && !String(c[1].key || '').startsWith('__learnstatus:')).length;
const cloudVal = (k) => cloud().rows.find(r => r.key === k)?.value;
let t = Date.parse('2027-01-01');
const cloudSet = (key, value) => {
  cloud().rows = cloud().rows.filter(r => r.key !== key);
  cloud().rows.push({ user_id: 'user-1', key, value, updated_at: new Date(t += 1000).toISOString() });
};
cloud().rows = [];
cloudSet('kana_learned_words', [{ id: 1, text: 'a' }]);
cloudSet('kana_selected_rows', [{ id: 'dashboard', label: 'Old label' }]);
cloudSet('kana_prefs', 'dark');
store.kana_learned_words = JSON.stringify([{ id: 1, text: 'stale local' }]);
console.log('\n--- startup ---');
ok('startup pull succeeded', (await sync.startupSync()) === true);
ok('opens on the cloud copy', JSON.parse(store.kana_learned_words)[0].text === 'a');
console.log('\n--- re-saves are not edits ---');
let before = upserts();
localStorage.setItem('kana_learned_words', JSON.stringify([{ id: 1, text: 'a' }]));
localStorage.setItem('kana_prefs', 'dark');
await sleep(900);
ok('no push', upserts() === before);
console.log('\n--- sidebarOrder goes up once, then rests ---');
before = upserts();
localStorage.setItem('kana_selected_rows', JSON.stringify([{ id: 'dashboard', label: 'Dashboard' }]));
await sleep(900);
ok('pushed once', upserts() === before + 1);
const reh = [];
const stop = sync.startPolling((k) => reh.push(k), 200);
await sleep(700);
ok('polling finds nothing', events.length === 0 && reh.length === 0 && reloads.n === 0);
// Banko Learn holds nothing in App state, so nothing is ever rehydrated: every
// incoming key is stored and announced for the page that shows it.
console.log('\n--- hot key from elsewhere ---');
cloudSet('kana_learned_words', [{ id: 1, text: 'a' }, { id: 2, text: 'from mac' }]);
await sleep(700);
ok('stored and announced in place', events.includes('kana_learned_words') && JSON.parse(store.kana_learned_words).length === 2 && reloads.n === 0);
before = upserts();
localStorage.setItem('kana_learned_words', JSON.stringify([{ id: 1, text: 'a' }, { id: 2, text: 'from mac' }]));
await sleep(900);
ok('echo not pushed', upserts() === before);
console.log('\n--- an App setting from elsewhere is applied in place ---');
cloudSet('kana_prefs', 'light');
await sleep(700);
ok('announced too', events.includes('kana_prefs') && localStorage.getItem('kana_prefs') === 'light');
console.log('\n--- a section-owned key from elsewhere ---');
cloudSet('kana_stats', ['from mac']);
await sleep(700);
ok('stored and announced', events.includes('kana_stats') && JSON.parse(localStorage.getItem('kana_stats'))[0] === 'from mac');
before = upserts();
localStorage.setItem('kana_stats', JSON.stringify(['written here']));
await sleep(900);
ok('a write here is sent, never held', upserts() === before + 1 && JSON.stringify(cloudVal('kana_stats')) === '["written here"]');
await sleep(4000);
ok('and the window is never reloaded', reloads.n === 0);
stop();
console.log('\n--- in-flight race ---');
localStorage.setItem('kana_stats', JSON.stringify(['v1']));
await sleep(750);
localStorage.setItem('kana_stats', JSON.stringify(['v2']));
await sleep(50);
ok('v2 still marked', sb.readDirtyKeys().has('kana_stats'));
await sleep(900);
ok('v2 lands and mark clears', JSON.stringify(cloudVal('kana_stats')) === '["v2"]' && !sb.readDirtyKeys().has('kana_stats'));
console.log('\n--- account clear leaves the cloud alone ---');
const n = cloud().rows.length;
const deletesBefore = cloud().calls.filter(c => c[0] === 'delete').length;
globalThis.__diag = () => {};
await clearAccountData().catch(() => {});
ok('the clear sent no deletes', cloud().calls.filter(c => c[0] === 'delete').length === deletesBefore);
ok('every row is still there', cloud().rows.length === n);
ok('the device is empty', localStorage.getItem('kana_learned_words') === null);
done();
